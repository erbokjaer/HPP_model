function F = reportFigures()
%REPORTFIGURES  Definitions of the report figures made by plotAll(Mode="report").
%
%   One entry per figure; each figure makes one point, so it shows only the
%   cases and signals needed for it, zoomed on the event. Fields:
%     name     file name (figures/report/<name>.pdf)
%     set      case set (results/<set>/)
%     what     the point the figure makes (also printed by plotAll)
%     cases    case names in the set, in legend order
%     labels   legend labels (TeX), same order; "" = case names
%     axes     cell: one string array of signals per axis, top to bottom.
%              Reference signals (P_ref, Q_ref, P_avail_*, P_bess_set) are
%              dashed; with several cases they take the case colour, with
%              one case every signal gets its own colour and a legend entry.
%     xlim     time window [s]
%     delta    true: plot the change from the value at t0 (no offsets
%              between cases with different operating points)
%     t0       reference time for delta [s]
%
%   Add a figure by adding an entry; signals: see logSignalNames in
%   buildHPP.m, plus "PF" (power factor at the POC).

    F = struct("name", {}, "set", {}, "what", {}, "cases", {}, "labels", {}, ...
               "axes", {}, "xlim", {}, "delta", {}, "t0", {});

    % ---- overview: nominal operation ----
    F(end+1) = fig("nominal_dispatch", "nominal", ...
        "Nominal operation: the plant ramps up after the wind step at 20 s (36 MW/min) and holds P_ref at the POC; the BESS covers the shortfall before the step and absorbs the surplus while ramping.", ...
        "nominal", "", {["P_ref", "P_poc"], ["P_avail_wpp", "P_wpp", "P_spp", "P_bess"]}, [2 60]);

    % ---- frequency response (Energinet DK1) ----
    F(end+1) = fig("freq_lfsm", "freq_step", ...
        "LFSM-O / LFSM-U: no response up to 50.2 Hz; beyond the thresholds 5 % droop on Pn (12 % of Pn for 0.3 Hz), within 0.3 s.", ...
        ["+0.2 Hz (LFSM-O limit)", "+0.5 Hz LFSM-O", "-0.5 Hz LFSM-U"], ["+0.2 Hz", "+0.5 Hz", "-0.5 Hz"], ...
        {"f", "P_poc"}, [49 55]);
    F(end+1) = fig("freq_fsm", "freq_step", ...
        "FSM (FCR delivery): 5 % droop with 10 mHz deadband, limited to 10 % of Pn, plus LFSM-O beyond 50.2 Hz.", ...
        ["+0.2 Hz FSM", "-0.2 Hz FSM", "+0.5 Hz FSM + LFSM-O"], ["+0.2 Hz", "-0.2 Hz", "+0.5 Hz (FSM + LFSM-O)"], ...
        {"f", "P_poc"}, [49 55]);
    F(end+1) = fig("freq_central_decentral", "freq_step", ...
        "Central (HPPC) against decentral (plant controller droop) frequency response to +0.2 Hz: about the same change at the POC; decentral reacts slightly earlier but overshoots and curtails wind, central uses the BESS and settles without overshoot.", ...
        ["+0.2 Hz FSM", "+0.2 Hz, decentral"], ["central (HPPC)", "decentral (plant controllers)"], ...
        {"P_poc", "P_wpp"}, [49 56], true, 49.9);

    % ---- P control at the POC with the ramp rate constraint ----
    F(end+1) = fig("ramp_steps", "hppc_p", ...
        "P_ref steps follow the ramp rate constraint of 20 % Pn/min (36 MW/min); +40 MW stops at the 180 MW export limit.", ...
        ["step -30 MW", "step +20 MW", "step +40 MW (limit)"], ["-30 MW", "+20 MW", "+40 MW"], ...
        {["P_poc", "P_ref"]}, [35 100]);
    F(end+1) = fig("ramp_rates", "hppc_p", ...
        "The ramp rate setting (1-20 % Pn/min) sets the slope; without the constraint the set-point is reached in about 1 s.", ...
        ["step -30 MW", "step -30 MW, 10 %/min", "step -30 MW, no ramp"], ["20 %/min", "10 %/min", "no limit"], ...
        {["P_poc", "P_ref"]}, [35 120]);
    F(end+1) = fig("ramp_dispatch", "hppc_p", ...
        "Dispatch during the ramps: the BESS takes the change first; wind is curtailed only when the BESS reaches its charge limit.", ...
        ["step -30 MW", "step +20 MW"], ["-30 MW", "+20 MW"], ...
        {"P_bess", ["P_wpp", "P_avail_wpp"]}, [35 100]);

    % ---- Q, voltage and power factor control at the POC ----
    F(end+1) = fig("q_steps", "hppc_qv", ...
        "Q control at the POC: Q_ref steps of +-30 Mvar, 90 % after 0.35 s, settled within 0.7 s (overshoot 6-10 Mvar, mostly from the plant and asset Q loops); the POC voltage follows.", ...
        ["Q step +30 Mvar", "Q step -30 Mvar"], ["+30 Mvar", "-30 Mvar"], ...
        {["Q_poc", "Q_ref"], "V_poc"}, [39 43]);
    F(end+1) = fig("v_control", "hppc_qv", ...
        "Voltage control after a 2 % grid voltage drop (plant controllers on a V-Q droop at the 33 kV busbar, HPPC trimming to the POC slope): Q on the slope, 90 % within 0.6 s (requirement 1 s), settled within 0.5 s (requirement 5 s) for slopes 2-7 % and SCR 3-10; Q control for comparison.", ...
        ["V ctrl 2 %, grid -2 %", "V ctrl, grid -2 %", "V ctrl, grid -2 %, SCR3", "V ctrl 7 %, grid -2 %, SCR3", "Q ctrl, grid -2 %"], ...
        ["slope 2 %, SCR 10", "slope 4 %, SCR 10", "slope 4 %, SCR 3", "slope 7 %, SCR 3", "Q control, SCR 10"], ...
        {"V_poc", "Q_poc"}, [39 43]);
    F(end+1) = fig("v_scr_mismatch", "hppc_qv", ...
        "Voltage control set for the wrong grid strength (SCR 10 on an SCR 3 grid): the fast busbar voltage control makes it robust; the first response is faster (90 % after 0.12 s instead of 0.40 s), overshoot and settling about the same.", ...
        ["V ctrl, grid -2 %, SCR3", "V ctrl, SCR3, set for SCR10"], ["set for SCR 3", "set for SCR 10"], ...
        {"Q_poc"}, [39 43]);
    F(end+1) = fig("v_qlimit", "hppc_qv", ...
        "Q limit at the POC in voltage control: a 10 % grid voltage drop (8 % rise) asks for more than +-0.33 pu; the plants' fast droop overshoots to about 70 Mvar, the HPPC pulls Q_poc back to exactly +-59.4 Mvar within about 20 s.", ...
        ["V ctrl, grid -10 % (Q limit)", "V ctrl, grid +8 % (Q limit)"], ["grid -10 %", "grid +8 %"], ...
        {"Q_poc", "V_poc"}, [35 90]);
    F(end+1) = fig("v_antiwindup", "hppc_qv", ...
        "Anti-windup over the plant limits: plants limited to 0.2 pu saturate during a 20 s grid voltage drop of 10 %; without anti-windup the HPPC order winds up and Q stays wrong (+16 Mvar, raising the voltage) for 9.5 s after the voltage returns, with it Q is back within 0.9 s.", ...
        ["V ctrl, plants limited, anti-windup", "V ctrl, plants limited, no anti-windup"], ["with anti-windup", "without anti-windup"], ...
        {"Q_poc", "V_poc"}, [35 75]);
    F(end+1) = fig("pf_control", "hppc_qv", ...
        "Power factor control: Q follows P at PF 0.95 (export / import), also while P ramps after the wind step.", ...
        ["Q 0", "PF 0.95 export", "PF 0.95 import"], ["Q control, Q_{ref} = 0", "PF 0.95 export", "PF 0.95 import"], ...
        {"P_poc", "Q_poc"}, [2 60]);

    % ---- fault ride-through (zoomed on the fault) ----
    F(end+1) = fig("frt_vq", "wt_frt", ...
        "Fault ride-through, 150 ms grid voltage dips at 45 s: reactive current injection supports the POC voltage.", ...
        ["dip 0.5", "dip 0.8", "dip 0.5 SCR3"], ["to 0.5 pu", "to 0.2 pu", "to 0.5 pu, SCR 3"], ...
        {"V_poc", "Q_poc"}, [44.9 46.0]);
    F(end+1) = fig("frt_p", "wt_frt", ...
        "Active power through the dip: P recovers within 0.5 s after clearing, without overshoot (HPPC P loop frozen during the dip).", ...
        ["no dip", "dip 0.5", "dip 0.8", "dip 0.5 SCR3"], ["no dip", "to 0.5 pu", "to 0.2 pu", "to 0.5 pu, SCR 3"], ...
        {"P_poc"}, [44.9 46.0]);

    % ---- SOC-aware BESS limits ----
    F(end+1) = fig("soc_derating", "bess_soc", ...
        "SOC-aware limits: the BESS discharge is derated linearly over 0.1 SOC above SOCmin, so a nearly empty BESS delivers less before the wind step.", ...
        ["SOC0 0.5", "SOC0 0.15", "at SOCmin"], ["SOC_0 = 0.5", "SOC_0 = 0.15", "SOC_0 = 0.1 (SOC_{min})"], ...
        {"P_bess", "P_poc"}, [2 40]);
    F(end+1) = fig("soc_step", "bess_soc", ...
        "A +20 MW step with a nearly empty BESS: the derated BESS limits the plant to 165 MW.", ...
        ["SOC0 0.5, +20 MW", "SOC0 0.15, +20 MW"], ["SOC_0 = 0.5", "SOC_0 = 0.15"], ...
        {["P_poc", "P_ref"], "P_bess"}, [35 100]);
end

function f = fig(name, set, what, cases, labels, axes, xl, delta, t0)
    if nargin < 8, delta = false; end
    if nargin < 9, t0 = NaN; end
    if isequal(labels, ""), labels = cases; end
    f = struct("name", name, "set", set, "what", what, "cases", string(cases), "labels", string(labels), ...
               "axes", {cellfun(@string, axes, "UniformOutput", false)}, "xlim", xl, "delta", delta, "t0", t0);
end
